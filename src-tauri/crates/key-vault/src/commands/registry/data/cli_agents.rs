//! Static CLI agent registry entries.

use super::types::{
    AcpSupport, CliAgentEntry, CliConfigFileEntry, CliConfigFormat, CliConfigPathKind,
};

const fn home_config(
    id: &'static str,
    label: &'static str,
    relative_path: &'static str,
    format: CliConfigFormat,
    secret_bearing: bool,
) -> CliConfigFileEntry {
    CliConfigFileEntry {
        id,
        label,
        path_kind: CliConfigPathKind::HomeRelative,
        relative_path,
        format,
        secret_bearing,
    }
}

const fn xdg_config(
    id: &'static str,
    label: &'static str,
    relative_path: &'static str,
    format: CliConfigFormat,
    secret_bearing: bool,
) -> CliConfigFileEntry {
    CliConfigFileEntry {
        id,
        label,
        path_kind: CliConfigPathKind::XdgConfigRelative,
        relative_path,
        format,
        secret_bearing,
    }
}

const fn app_data_config(
    id: &'static str,
    label: &'static str,
    relative_path: &'static str,
    format: CliConfigFormat,
    secret_bearing: bool,
) -> CliConfigFileEntry {
    CliConfigFileEntry {
        id,
        label,
        path_kind: CliConfigPathKind::AppDataRelative,
        relative_path,
        format,
        secret_bearing,
    }
}

fn goose_config(
    id: &'static str,
    label: &'static str,
    _xdg_relative_path: &'static str,
    _windows_relative_path: &'static str,
    format: CliConfigFormat,
    secret_bearing: bool,
) -> CliConfigFileEntry {
    #[cfg(target_os = "windows")]
    let config = app_data_config(id, label, _windows_relative_path, format, secret_bearing);

    #[cfg(not(target_os = "windows"))]
    let config = xdg_config(id, label, _xdg_relative_path, format, secret_bearing);

    config
}
