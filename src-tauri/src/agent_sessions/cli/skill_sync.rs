/// Sync project conventions (`.orgii/agent-rules.md`) to each CLI agent's
/// native rules file.
///
/// Replaces the old `sync_conventions_to_cursorrules()` which wrote to the
/// deprecated `.cursorrules` file (which Cursor agent mode ignores).
pub fn sync_conventions_for_agent(agent: &ModelType, workspace_path: &Path) -> Vec<PathBuf> {
    let conventions_path = workspace_path.join(".orgii").join("agent-rules.md");
    let content = match fs::read_to_string(&conventions_path) {
        Ok(content) if !content.trim().is_empty() => content,
        _ => return Vec::new(),
    };

    let targets = convention_targets_for_agent(agent, workspace_path);
    let mut written: Vec<PathBuf> = Vec::new();

    for target in targets {
        // Skip if a non-orgii file already exists at this path
        if target.exists() {
            let is_ours = fs::read_to_string(&target)
                .map(|existing| existing.contains(ORGII_MARKER))
                .unwrap_or(false);
            if !is_ours {
                continue;
            }
        }

        match write_rule_file(&target, &content) {
            Ok(()) => {
                tracing::info!("[skill_sync] Synced conventions to {}", target.display());
                written.push(target);
            }
            Err(err) => {
                tracing::warn!(
                    "[skill_sync] Failed to sync conventions to {}: {}",
                    target.display(),
                    err
                );
            }
        }
    }

    written
}

/// Determine convention file paths for each agent type.
fn convention_targets_for_agent(agent: &ModelType, workspace_path: &Path) -> Vec<PathBuf> {
    match agent {
        ModelType::CursorCli => {
            vec![workspace_path
                .join(".cursor")
                .join("rules")
                .join("orgii-conventions.mdc")]
        }
        ModelType::ClaudeCode => {
            vec![workspace_path
                .join(".claude")
                .join("rules")
                .join("orgii-conventions.md")]
        }
        ModelType::Codex => Vec::new(),
        ModelType::Copilot => {
            vec![workspace_path
                .join(".github")
                .join("instructions")
                .join("orgii-conventions.instructions.md")]
        }
        ModelType::Kiro => Vec::new(),
        _ => Vec::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::build_skills_prompt_injection;

    #[test]
    fn provider_skill_catalog_is_stable_bounded_and_keeps_load_paths() {
        let workspace = tempfile::tempdir().expect("workspace");
        for index in 0..80 {
            let skill_dir = workspace
                .path()
                .join(".agents/skills")
                .join(format!("skill-{index:03}"));
            std::fs::create_dir_all(&skill_dir).expect("create skill dir");
            std::fs::write(
                skill_dir.join("SKILL.md"),
                format!(
                    "---\nname: skill-{index:03}\ndescription: {}\n---\n\nBody {index}",
                    "description ".repeat(80)
                ),
            )
            .expect("write skill");
        }

        let first = build_skills_prompt_injection(workspace.path(), true, &[])
            .expect("provider skill catalog");
        let second = build_skills_prompt_injection(workspace.path(), true, &[])
            .expect("provider skill catalog");
        assert_eq!(
            first, second,
            "catalog must be byte-stable for digest reuse"
        );
        assert!(first.contains("skill-000"));
        assert!(first.contains("SKILL.md"));
        assert!(
            first.chars().count() <= 12_000,
            "catalog must stay near its 8k entry budget: {} chars",
            first.chars().count()
        );
    }
}
