/// Build the formatted skills content shared by all agents.
fn build_skills_content(skills: &[SkillInfo]) -> String {
    let mut skills = skills.iter().collect::<Vec<_>>();
    skills.sort_by(|left, right| {
        left.name
            .cmp(&right.name)
            .then_with(|| left.path.cmp(&right.path))
    });

    // Keep discovery byte-stable and bounded. Full SKILL.md bodies are loaded
    // only after the provider selects a matching entry.
    let mut description_budget = PROVIDER_SKILL_DESCRIPTION_MAX_CHARS;
    let render_lines = |description_budget: usize| -> Vec<String> {
        skills
            .iter()
            .map(|skill| {
                let desc = if skill.description.is_empty() {
                    "No description".to_string()
                } else {
                    agent_core::utils::safe_truncate_chars_to_string(
                        &skill.description,
                        description_budget,
                    )
                };
                format!(
                    "- **{}** ({}): {}\n  Path: `{}`",
                    skill.name,
                    skill.source,
                    desc,
                    skill.path.display()
                )
            })
            .collect()
    };
    let mut summary_lines = render_lines(description_budget);
    let mut rendered_chars = summary_lines
        .iter()
        .map(|line| line.chars().count())
        .sum::<usize>();
    if rendered_chars > PROVIDER_SKILL_CATALOG_CHAR_BUDGET && !skills.is_empty() {
        let overflow = rendered_chars - PROVIDER_SKILL_CATALOG_CHAR_BUDGET;
        description_budget = description_budget
            .saturating_sub(overflow.div_ceil(skills.len()))
            .max(20);
        summary_lines = render_lines(description_budget);
        rendered_chars = summary_lines
            .iter()
            .map(|line| line.chars().count())
            .sum::<usize>();
    }
    if rendered_chars > PROVIDER_SKILL_CATALOG_CHAR_BUDGET {
        summary_lines = skills
            .iter()
            .map(|skill| format!("- **{}** — `{}`", skill.name, skill.path.display()))
            .collect();
    }

    format!(
        "## Skills (mandatory)\n\n\
         Before replying: scan the skill descriptions below.\n\
         - If exactly one skill clearly applies: read its SKILL.md using read_file, then follow it.\n\
         - If multiple could apply: choose the most specific one, then read/follow it.\n\
         - If none clearly apply: do not read any SKILL.md.\n\
         Constraints: never read more than one skill up front; only read after selecting.\n\n\
         {}",
        summary_lines.join("\n")
    )
}

/// Write a rule file with the appropriate wrapper for its format.
fn write_rule_file(target: &Path, content: &str) -> Result<(), String> {
    // Ensure parent directory exists
    if let Some(parent) = target.parent() {
        if !parent.exists() {
            fs::create_dir_all(parent).map_err(|err| {
                format!("Failed to create directory {}: {}", parent.display(), err)
            })?;
        }
    }

    let ext = target.extension().and_then(|e| e.to_str()).unwrap_or("");
    let wrapped = match ext {
        "mdc" => format_mdc(content),
        _ => format_markdown(content),
    };

    fs::write(target, wrapped)
        .map_err(|err| format!("Failed to write {}: {}", target.display(), err))
}

/// Wrap content as a Cursor `.mdc` file with `alwaysApply: true` frontmatter.
fn format_mdc(content: &str) -> String {
    format!(
        "---\ndescription: Skills injected by orgii for coding sessions\nalwaysApply: true\n---\n\n{marker}\n\n{content}",
        marker = ORGII_MARKER,
        content = content,
    )
}

/// Wrap content as a plain markdown file with the orgii marker.
fn format_markdown(content: &str) -> String {
    format!(
        "{marker}\n\n{content}",
        marker = ORGII_MARKER,
        content = content,
    )
}

